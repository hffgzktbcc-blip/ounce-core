// GIFT-128 from Banik, Pandey, Peyrin, Sasaki, Sim, Todo, "GIFT: A Small Present" (CHES 2017). This program implements GIFT-128
// as the bitsliced round function, 6-bit round-constant LFSR and 16-bit-word key schedule described in the GIFT-COFB
// specification (NIST Lightweight Cryptography submission by Banik, Chakraborti, Iwata, Minematsu, Nandi, Peyrin, Sasaki, Sim,
// Todo), written from that description: 40 rounds of
// SubCells, PermBits (one 32-bit permutation per slice, Table 2.2 of the specification) and AddRoundKey.
// Checks the two GIFT-128 test vectors printed in that specification, the 40 round constants (generated by the LFSR) against
// the specification's table, and that the four permutation rows are bijections. No decryption is implemented.
// The tables and vectors are data copied as numbers; no code was copied.
#include "ounce_paper.h"

// PermBits table (Table 2.2): PERM[s][k] is the row of slice s read from index 31 down to 0 (k = 31 - index).
static const u8 PERM[4][32] = {
    {29, 25, 21, 17, 13, 9, 5, 1, 30, 26, 22, 18, 14, 10, 6, 2, 31, 27, 23, 19, 15, 11, 7, 3, 28, 24, 20, 16, 12, 8, 4, 0},
    {30, 26, 22, 18, 14, 10, 6, 2, 31, 27, 23, 19, 15, 11, 7, 3, 28, 24, 20, 16, 12, 8, 4, 0, 29, 25, 21, 17, 13, 9, 5, 1},
    {31, 27, 23, 19, 15, 11, 7, 3, 28, 24, 20, 16, 12, 8, 4, 0, 29, 25, 21, 17, 13, 9, 5, 1, 30, 26, 22, 18, 14, 10, 6, 2},
    {28, 24, 20, 16, 12, 8, 4, 0, 29, 25, 21, 17, 13, 9, 5, 1, 30, 26, 22, 18, 14, 10, 6, 2, 31, 27, 23, 19, 15, 11, 7, 3},
};
// Round constants of rounds 1..48 from the specification's table (only the first 40 are used).
static const u8 RC[48] = {
    0x01, 0x03, 0x07, 0x0f, 0x1f, 0x3e, 0x3d, 0x3b, 0x37, 0x2f, 0x1e, 0x3c, 0x39, 0x33, 0x27, 0x0e,
    0x1d, 0x3a, 0x35, 0x2b, 0x16, 0x2c, 0x18, 0x30, 0x21, 0x02, 0x05, 0x0b, 0x17, 0x2e, 0x1c, 0x38,
    0x31, 0x23, 0x06, 0x0d, 0x1b, 0x36, 0x2d, 0x1a, 0x34, 0x29, 0x12, 0x24, 0x08, 0x11, 0x22, 0x04
};
typedef struct { const char *name; const char *key, *pt, *ct; } vec;
static const vec VEC[] = {
    {"GIFT-128 test vector 1", "00 01 02 03 04 05 06 07 08 09 0A 0B 0C 0D 0E 0F", "00 01 02 03 04 05 06 07 08 09 0A 0B 0C 0D 0E 0F", "A9 4A F7 F9 BA 18 1D F9 B2 B0 0E B7 DB FA 93 DF"},
    {"GIFT-128 test vector 2", "E0 84 1F 8F B9 07 83 13 6A A8 B7 F1 92 F5 C4 74", "E4 91 C6 65 52 20 31 CF 03 3B F7 1B 99 89 EC B3", "33 31 EF C3 A6 60 4F 95 99 ED 42 B7 DB C0 2A 38"},
};
#define NVEC ((int)(sizeof VEC / sizeof VEC[0]))


#ifndef GIFT_ROUNDS
#define GIFT_ROUNDS 40
#endif

static int hexbytes(const char *s, u8 *out) {   // hex digits (spaces ignored) -> bytes; returns byte count
    int n = 0, half = 0, cur = 0;
    for (; *s; s++) {
        int d;
        if (*s >= '0' && *s <= '9') d = *s - '0'; else if (*s >= 'a' && *s <= 'f') d = *s - 'a' + 10; else if (*s >= 'A' && *s <= 'F') d = *s - 'A' + 10; else continue;
        cur = cur * 16 + d;
        if (half) { out[n++] = (u8)cur; cur = 0; }
        half ^= 1;
    }
    return n;
}
static u32 be32(const u8 *p) { return (u32)p[0] << 24 | (u32)p[1] << 16 | (u32)p[2] << 8 | p[3]; }
static void put_be32(u8 *p, u32 v) { p[0] = (u8)(v >> 24); p[1] = (u8)(v >> 16); p[2] = (u8)(v >> 8); p[3] = (u8)v; }
static u16 ror16(u16 x, int r) { return (u16)((x >> r) | (x << (16 - r))); }

// PermBits: the new bit at index idx of slice s is the old bit PERM[s][31 - idx] (the table's row s, read from index 31 down to 0).
static u32 permute(int s, u32 x) {
    u32 y = 0;
    for (int idx = 0; idx < 32; idx++) y |= ((x >> PERM[s][31 - idx]) & 1u) << idx;
    return y;
}

static void gift128(const u8 *key, const u8 *in, u8 *out) {
    u32 S0 = be32(in), S1 = be32(in + 4), S2 = be32(in + 8), S3 = be32(in + 12);
    u16 W[8]; for (int i = 0; i < 8; i++) W[i] = (u16)(key[2 * i] << 8 | key[2 * i + 1]);
    u32 c = 0;   // 6-bit constant LFSR c5..c0, updated before use
    for (int r = 0; r < GIFT_ROUNDS; r++) {
        // SubCells
        S1 ^= S0 & S2; S0 ^= S1 & S3; S2 ^= S0 | S1; S3 ^= S2; S1 ^= S3; S3 = ~S3; S2 ^= S0 & S1;
        u32 t = S0; S0 = S3; S3 = t;   // {S0,S1,S2,S3} <- {S3,S1,S2,S0}
        // PermBits
        S0 = permute(0, S0); S1 = permute(1, S1); S2 = permute(2, S2); S3 = permute(3, S3);
        // AddRoundKey: U = W2 || W3 into S2, V = W6 || W7 into S1, constant into S3
        c = ((c << 1) & 0x3f) | (((c >> 5) ^ (c >> 4) ^ 1) & 1);
        S2 ^= (u32)W[2] << 16 | W[3];
        S1 ^= (u32)W[6] << 16 | W[7];
        S3 ^= 0x80000000u ^ c;
        // key state update
        u16 n0 = ror16(W[6], 2), n1 = ror16(W[7], 12);
        W[7] = W[5]; W[6] = W[4]; W[5] = W[3]; W[4] = W[2]; W[3] = W[1]; W[2] = W[0]; W[1] = n1; W[0] = n0;
    }
    put_be32(out, S0); put_be32(out + 4, S1); put_be32(out + 8, S2); put_be32(out + 12, S3);
}

int paper_main(void) {
    int ok = 1;
    // round constants from the LFSR against the specification's table
    int cg = 0; u32 c = 0;
    for (int r = 0; r < 40; r++) { c = ((c << 1) & 0x3f) | (((c >> 5) ^ (c >> 4) ^ 1) & 1); cg += c == RC[r]; }
    pstr(cg == 40 ? "PASS " : "FAIL "); pdec(cg); pstr(" of 40 round constants match the specification's table\n");
    ok &= cg == 40;
    // each permutation row must be a bijection on 0..31
    int pg = 0;
    for (int s = 0; s < 4; s++) { u32 seen = 0; for (int i = 0; i < 32; i++) seen |= 1u << PERM[s][i]; pg += seen == 0xffffffffu; }
    pstr(pg == 4 ? "PASS " : "FAIL "); pdec(pg); pstr(" of 4 permutation rows are bijections\n");
    ok &= pg == 4;
    int good = 0;
    for (int v = 0; v < NVEC; v++) {
        const vec *e = &VEC[v];
        u8 key[16], pt[16], want[16], got[16];
        if (hexbytes(e->key, key) != 16 || hexbytes(e->pt, pt) != 16 || hexbytes(e->ct, want) != 16) { pstr("FAIL bad vector sizes\n"); return 1; }
        gift128(key, pt, got);
        good += pcheck_bytes(e->name, got, want, 16);
    }
    pstr("test vectors: "); pdec(good); pstr(" of "); pdec(NVEC); pstr(" match\n");
    ok &= good == NVEC;
    pstr(ok ? "PASS\n" : "FAIL\n");
    return ok ? 0 : 1;
}
