#ifndef CLEFIA_Q16
#define CLEFIA_Q16 0x243f   // Q(16) = (pi - 3) * 2^16; P(16) = 0xb7e1 = (e - 2) * 2^16
#endif
#define CLEFIA_P16 0xb7e1

static u8 gmul(u8 a, u8 b) {   // multiplication in GF(2^8) modulo z^8 + z^4 + z^3 + z^2 + 1
    u8 r = 0;
    while (b) { if (b & 1) r ^= a; a = (u8)((a << 1) ^ ((a & 0x80) ? 0x1d : 0)); b >>= 1; }
    return r;
}
static u32 F0(u32 rk, u32 x) {
    u32 t = rk ^ x;
    u8 t0 = S0[t >> 24], t1 = S1[(t >> 16) & 255], t2 = S0[(t >> 8) & 255], t3 = S1[t & 255];
    u8 y0 = t0 ^ gmul(2, t1) ^ gmul(4, t2) ^ gmul(6, t3);
    u8 y1 = gmul(2, t0) ^ t1 ^ gmul(6, t2) ^ gmul(4, t3);
    u8 y2 = gmul(4, t0) ^ gmul(6, t1) ^ t2 ^ gmul(2, t3);
    u8 y3 = gmul(6, t0) ^ gmul(4, t1) ^ gmul(2, t2) ^ t3;
    return (u32)y0 << 24 | (u32)y1 << 16 | (u32)y2 << 8 | y3;
}
static u32 F1(u32 rk, u32 x) {
    u32 t = rk ^ x;
    u8 t0 = S1[t >> 24], t1 = S0[(t >> 16) & 255], t2 = S1[(t >> 8) & 255], t3 = S0[t & 255];
    u8 y0 = t0 ^ gmul(8, t1) ^ gmul(2, t2) ^ gmul(10, t3);
    u8 y1 = gmul(8, t0) ^ t1 ^ gmul(10, t2) ^ gmul(2, t3);
    u8 y2 = gmul(2, t0) ^ gmul(10, t1) ^ t2 ^ gmul(8, t3);
    u8 y3 = gmul(10, t0) ^ gmul(2, t1) ^ gmul(8, t2) ^ t3;
    return (u32)y0 << 24 | (u32)y1 << 16 | (u32)y2 << 8 | y3;
}
// GFN_{4,r}; if states != 0 it receives the state at the start of every round.
static void gfn4(const u32 *rk, int r, const u32 *x, u32 *y, u32 (*states)[4]) {
    u32 t0 = x[0], t1 = x[1], t2 = x[2], t3 = x[3];
    for (int i = 0; i < r; i++) {
        if (states) { states[i][0] = t0; states[i][1] = t1; states[i][2] = t2; states[i][3] = t3; }
        t1 ^= F0(rk[2 * i], t0); t3 ^= F1(rk[2 * i + 1], t2);
        u32 s = t0; t0 = t1; t1 = t2; t2 = t3; t3 = s;
    }
    y[0] = t3; y[1] = t0; y[2] = t1; y[3] = t2;
}
static void gfn4_inv(const u32 *rk, int r, const u32 *x, u32 *y) {
    u32 t0 = x[0], t1 = x[1], t2 = x[2], t3 = x[3];
    for (int i = 0; i < r; i++) {
        t1 ^= F0(rk[2 * (r - i) - 2], t0); t3 ^= F1(rk[2 * (r - i) - 1], t2);
        u32 s = t3; t3 = t2; t2 = t1; t1 = t0; t0 = s;
    }
    y[0] = t1; y[1] = t2; y[2] = t3; y[3] = t0;
}
static void gfn8(const u32 *rk, int r, const u32 *x, u32 *y) {
    u32 t[8]; for (int i = 0; i < 8; i++) t[i] = x[i];
    for (int i = 0; i < r; i++) {
        t[1] ^= F0(rk[4 * i], t[0]); t[3] ^= F1(rk[4 * i + 1], t[2]);
        t[5] ^= F0(rk[4 * i + 2], t[4]); t[7] ^= F1(rk[4 * i + 3], t[6]);
        u32 s = t[0]; for (int k = 0; k < 7; k++) t[k] = t[k + 1]; t[7] = s;
    }
    y[0] = t[7]; for (int k = 1; k < 8; k++) y[k] = t[k - 1];
}
// DoubleSwap on a 128-bit value held as four words: X[7-63] | X[121-127] | X[0-6] | X[64-120] (bit 0 = most significant).
static void sigma(u32 *x) {
    u64 hi = (u64)x[0] << 32 | x[1], lo = (u64)x[2] << 32 | x[3];
    u64 nh = (hi << 7) | (lo & 0x7f), nl = ((hi >> 57) << 57) | (lo >> 7);
    x[0] = (u32)(nh >> 32); x[1] = (u32)nh; x[2] = (u32)(nl >> 32); x[3] = (u32)nl;
}
// Constants CON_k[0 .. n-1]: T <- IV, then two constants per step and T <- T * z^{-1} in GF(2^16) (polynomial 0x1a831).
static void gen_con(u16 iv, int n, u32 *con) {
    u16 T = iv;
    for (int i = 0; i < n / 2; i++) {
        u16 nt = (u16)~T;
        con[2 * i] = (u32)(T ^ CLEFIA_P16) << 16 | (u16)((nt << 1) | (nt >> 15));
        con[2 * i + 1] = (u32)(nt ^ CLEFIA_Q16) << 16 | (u16)((T << 8) | (T >> 8));
        T = (u16)((T & 1) ? ((T ^ 0x1a831) >> 1) : (T >> 1));
    }
}

typedef struct { int bits, r; u32 WK[4], RK[52], L[8]; } sched;

static void key_schedule(int bits, const u32 *K, const u32 *con, sched *s) {
    s->bits = bits;
    if (bits == 128) {
        s->r = 18;
        gfn4(con, 12, K, s->L, 0);
        for (int i = 0; i < 4; i++) s->WK[i] = K[i];
        u32 L[4] = { s->L[0], s->L[1], s->L[2], s->L[3] };
        for (int i = 0; i < 9; i++) {
            u32 T[4]; for (int k = 0; k < 4; k++) T[k] = L[k] ^ con[24 + 4 * i + k];
            sigma(L);
            if (i & 1) for (int k = 0; k < 4; k++) T[k] ^= K[k];
            for (int k = 0; k < 4; k++) s->RK[4 * i + k] = T[k];
        }
    } else {
        s->r = bits == 192 ? 22 : 26;
        u32 KL[4] = { K[0], K[1], K[2], K[3] }, KR[4];
        if (bits == 192) { KR[0] = K[4]; KR[1] = K[5]; KR[2] = ~K[0]; KR[3] = ~K[1]; }
        else { for (int k = 0; k < 4; k++) KR[k] = K[4 + k]; }
        u32 in[8], L[8];
        for (int k = 0; k < 4; k++) { in[k] = KL[k]; in[4 + k] = KR[k]; }
        gfn8(con, 10, in, L);
        for (int k = 0; k < 8; k++) s->L[k] = L[k];
        for (int k = 0; k < 4; k++) s->WK[k] = KL[k] ^ KR[k];
        u32 *LL = L, *LR = L + 4;
        int n = bits == 192 ? 11 : 13;
        for (int i = 0; i < n; i++) {
            u32 T[4];
            if ((i & 3) < 2) {
                for (int k = 0; k < 4; k++) T[k] = LL[k] ^ con[40 + 4 * i + k];
                sigma(LL);
                if (i & 1) for (int k = 0; k < 4; k++) T[k] ^= KR[k];
            } else {
                for (int k = 0; k < 4; k++) T[k] = LR[k] ^ con[40 + 4 * i + k];
                sigma(LR);
                if (i & 1) for (int k = 0; k < 4; k++) T[k] ^= KL[k];
            }
            for (int k = 0; k < 4; k++) s->RK[4 * i + k] = T[k];
        }
    }
}
static void encrypt(const sched *s, const u32 *P, u32 *C, u32 (*states)[4], u32 *out) {
    u32 T[4] = { P[0], P[1] ^ s->WK[0], P[2], P[3] ^ s->WK[1] }, Y[4];
    gfn4(s->RK, s->r, T, Y, states);
    for (int k = 0; k < 4; k++) out[k] = Y[k];
    C[0] = Y[0]; C[1] = Y[1] ^ s->WK[2]; C[2] = Y[2]; C[3] = Y[3] ^ s->WK[3];
}
static void decrypt(const sched *s, const u32 *C, u32 *P) {
    u32 T[4] = { C[0], C[1] ^ s->WK[2], C[2], C[3] ^ s->WK[3] }, Y[4];
    gfn4_inv(s->RK, s->r, T, Y);
    P[0] = Y[0]; P[1] = Y[1] ^ s->WK[0]; P[2] = Y[2]; P[3] = Y[3] ^ s->WK[1];
}
static void wbytes(u8 *b, const u32 *w, int n) { for (int i = 0; i < n; i++) { b[4*i] = (u8)(w[i] >> 24); b[4*i+1] = (u8)(w[i] >> 16); b[4*i+2] = (u8)(w[i] >> 8); b[4*i+3] = (u8)w[i]; } }
static int same(const u32 *a, const u32 *b, int n) { for (int i = 0; i < n; i++) if (a[i] != b[i]) return 0; return 1; }
static int count_words(const char *what, const u32 *got, const u32 *want, int n, int bits) {
    int g = 0; for (int i = 0; i < n; i++) g += got[i] == want[i];
    pstr(g == n ? "PASS " : "FAIL "); pstr("CLEFIA-"); pdec(bits); pstr(" "); pstr(what); pstr(": ");
    pdec(g); pstr(" of "); pdec(n); pstr(" words match\n"); return g == n;
}

int paper_main(void) {
    int ok = 1;
    static const u16 IV[3] = { 0x428a, 0x7137, 0xb5c0 };
    static const int NCON[3] = { 60, 84, 92 };
    static const u32 *TAB[3] = { CONTAB128, CONTAB192, CONTAB256 };
    u32 con[3][92];
    int consgood = 0, consn = 0;
    for (int k = 0; k < 3; k++) {
        gen_con(IV[k], NCON[k], con[k]);
        int g = 0; for (int i = 0; i < NCON[k]; i++) g += con[k][i] == TAB[k][i];
        consgood += g; consn += NCON[k];
        pstr(g == NCON[k] ? "PASS " : "FAIL "); pstr("constants CON_"); pdec(128 + 64 * k); pstr(": ");
        pdec(g); pstr(" of "); pdec(NCON[k]); pstr(" match Table "); pdec(7 + k); pstr("\n");
    }
    ok &= consgood == consn;
    int vgood = 0;
    for (int k = 0; k < 3; k++) {
        const vec *v = &VEC[k];
        sched s; key_schedule(v->bits, v->key, con[k], &s);
        int nrk = 2 * v->r, nl = v->bits == 128 ? 4 : 8;
        int a = count_words("L (LL | LR)", s.L, v->L, nl, v->bits);
        int b = count_words("whitening keys", s.WK, v->WK, 4, v->bits);
        int c = count_words("round keys", s.RK, v->RK, nrk, v->bits);
        u32 C[4], out[4], states[26][4], P2[4];
        encrypt(&s, v->pt, C, states, out);
        int sg = 0; for (int i = 0; i < v->r; i++) sg += same(states[i], v->states[i], 4);
        pstr(sg == v->r ? "PASS " : "FAIL "); pstr("CLEFIA-"); pdec(v->bits); pstr(" round-start states: ");
        pdec(sg); pstr(" of "); pdec(v->r); pstr(" match\n");
        int d = same(out, v->out, 4);
        u8 gb[16], wb[16]; wbytes(gb, C, 4); wbytes(wb, v->ct, 4);
        char nm[32] = "CLEFIA-000 ciphertext"; nm[7] = (char)('0' + v->bits / 100); nm[8] = (char)('0' + v->bits / 10 % 10); nm[9] = (char)('0' + v->bits % 10);
        int e = pcheck_bytes(nm, gb, wb, 16);
        decrypt(&s, C, P2);
        int f = same(P2, v->pt, 4);
        pstr(f ? "PASS " : "FAIL "); pstr("CLEFIA-"); pdec(v->bits); pstr(" decrypt round trip\n");
        vgood += a && b && c && sg == v->r && d && e && f;
    }
    ok &= vgood == 3;
    pstr("key sizes fully matching: "); pdec(vgood); pstr(" of 3\n");
    pstr(ok ? "PASS\n" : "FAIL\n");
    return ok ? 0 : 1;
}
