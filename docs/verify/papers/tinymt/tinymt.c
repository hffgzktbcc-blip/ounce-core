#ifndef TMT32_SH1
#define TMT32_SH1 10          // TinyMT32 recurrence shifts: sh0 = 1, sh1 = 10
#endif
#define TMT32_SH0 1
#ifndef TMT64_SH0
#define TMT64_SH0 12          // TinyMT64 recurrence shifts: sh0 = 12, sh1 = 11
#endif
#define TMT64_SH1 11

// ---------- TinyMT32 ----------
static const u32 M32_MAT1 = 0x8f7011eeU, M32_MAT2 = 0xfc78ff1fU, M32_TMAT = 0x3793fdffU;
static u32 s32[4];
static void t32_next(void) {
    u32 y = s32[3];
    u32 x = (s32[0] & 0x7fffffffU) ^ s32[1] ^ s32[2];
    x ^= x << TMT32_SH0;
    y ^= (y >> TMT32_SH0) ^ x;
    s32[0] = s32[1]; s32[1] = s32[2]; s32[2] = x ^ (y << TMT32_SH1); s32[3] = y;
    if (y & 1U) { s32[1] ^= M32_MAT1; s32[2] ^= M32_MAT2; }
}
static u32 t32_temper(void) {
    u32 t0 = s32[3], t1 = s32[0] + (s32[2] >> 8);
    t0 ^= t1;
    if (t1 & 1U) t0 ^= M32_TMAT;
    return t0;
}
static u32 t32_u32(void) { t32_next(); return t32_temper(); }
static void t32_certify(void) {
    if ((s32[0] & 0x7fffffffU) == 0 && !s32[1] && !s32[2] && !s32[3]) { s32[0] = 'T'; s32[1] = 'I'; s32[2] = 'N'; s32[3] = 'Y'; }
}
static void t32_init(u32 seed) {
    s32[0] = seed; s32[1] = M32_MAT1; s32[2] = M32_MAT2; s32[3] = M32_TMAT;
    for (u32 i = 1; i < 8; i++) s32[i & 3] ^= i + 1812433253U * (s32[(i - 1) & 3] ^ (s32[(i - 1) & 3] >> 30));
    t32_certify();
    for (int i = 0; i < 8; i++) t32_next();
}
static u32 t32_f1(u32 x) { return (x ^ (x >> 27)) * 1664525U; }
static u32 t32_f2(u32 x) { return (x ^ (x >> 27)) * 1566083941U; }
static void t32_init_array(const u32 *key, u32 len) {
    u32 *st = s32, r, i, j, count = len + 1 > 8 ? len + 1 : 8;
    st[0] = 0; st[1] = M32_MAT1; st[2] = M32_MAT2; st[3] = M32_TMAT;
    r = t32_f1(st[0] ^ st[1] ^ st[3]);
    st[1] += r; r += len; st[2] += r; st[0] = r;
    count--;
    for (i = 1, j = 0; j < count && j < len; j++) {
        r = t32_f1(st[i] ^ st[(i + 1) & 3] ^ st[(i + 3) & 3]);
        st[(i + 1) & 3] += r; r += key[j] + i; st[(i + 2) & 3] += r; st[i] = r; i = (i + 1) & 3;
    }
    for (; j < count; j++) {
        r = t32_f1(st[i] ^ st[(i + 1) & 3] ^ st[(i + 3) & 3]);
        st[(i + 1) & 3] += r; r += i; st[(i + 2) & 3] += r; st[i] = r; i = (i + 1) & 3;
    }
    for (j = 0; j < 4; j++) {
        r = t32_f2(st[i] + st[(i + 1) & 3] + st[(i + 3) & 3]);
        st[(i + 1) & 3] ^= r; r -= i; st[(i + 2) & 3] ^= r; st[i] = r; i = (i + 1) & 3;
    }
    t32_certify();
    for (int k = 0; k < 8; k++) t32_next();
}

// ---------- TinyMT64 ----------
static const u32 M64_MAT1 = 0xfa051f40U, M64_MAT2 = 0xffd0fff4U;
static const u64 M64_TMAT = 0x58d02ffeffbfffbcULL;
static u64 s64[2];
static void t64_next(void) {
    s64[0] &= 0x7fffffffffffffffULL;
    u64 x = s64[0] ^ s64[1];
    x ^= x << TMT64_SH0; x ^= x >> 32; x ^= x << 32; x ^= x << TMT64_SH1;
    s64[0] = s64[1]; s64[1] = x;
    if (x & 1ULL) { s64[0] ^= M64_MAT1; s64[1] ^= (u64)M64_MAT2 << 32; }
}
static u64 t64_temper(void) {
    u64 x = s64[0] + s64[1];
    x ^= s64[0] >> 8;
    if (x & 1ULL) x ^= M64_TMAT;
    return x;
}
static u64 t64_u64(void) { t64_next(); return t64_temper(); }
static void t64_certify(void) { if ((s64[0] & 0x7fffffffffffffffULL) == 0 && s64[1] == 0) { s64[0] = 'T'; s64[1] = 'M'; } }
static void t64_init(u64 seed) {
    s64[0] = seed ^ ((u64)M64_MAT1 << 32); s64[1] = (u64)M64_MAT2 ^ M64_TMAT;
    for (u32 i = 1; i < 8; i++) s64[i & 1] ^= i + 6364136223846793005ULL * (s64[(i - 1) & 1] ^ (s64[(i - 1) & 1] >> 62));
    t64_certify();
}
static u64 t64_f1(u64 x) { return (x ^ (x >> 59)) * 2173292883993ULL; }
static u64 t64_f2(u64 x) { return (x ^ (x >> 59)) * 58885565329898161ULL; }
static void t64_init_array(const u64 *key, u32 len) {
    u64 st[4], r; u32 i, j, count = len + 1 > 8 ? len + 1 : 8;
    st[0] = 0; st[1] = M64_MAT1; st[2] = M64_MAT2; st[3] = M64_TMAT;
    r = t64_f1(st[0] ^ st[1] ^ st[3]);
    st[1] += r; r += len; st[2] += r; st[0] = r;
    count--;
    for (i = 1, j = 0; j < count && j < len; j++) {
        r = t64_f1(st[i] ^ st[(i + 1) & 3] ^ st[(i + 3) & 3]);
        st[(i + 1) & 3] += r; r += key[j] + i; st[(i + 2) & 3] += r; st[i] = r; i = (i + 1) & 3;
    }
    for (; j < count; j++) {
        r = t64_f1(st[i] ^ st[(i + 1) & 3] ^ st[(i + 3) & 3]);
        st[(i + 1) & 3] += r; r += i; st[(i + 2) & 3] += r; st[i] = r; i = (i + 1) & 3;
    }
    for (j = 0; j < 4; j++) {
        r = t64_f2(st[i] + st[(i + 1) & 3] + st[(i + 3) & 3]);
        st[(i + 1) & 3] ^= r; r -= i; st[(i + 2) & 3] ^= r; st[i] = r; i = (i + 1) & 3;
    }
    s64[0] = st[0] ^ st[1]; s64[1] = st[2] ^ st[3];
    t64_certify();
}

// ---------- exact decimal printing of num / 2^shift, rounded half to even like printf ----------
static int fmt_frac(char *buf, u64 num, int shift, int decimals) {
    unsigned __int128 p10 = 1; for (int i = 0; i < decimals; i++) p10 *= 10;
    u64 ip = num >> shift, fr = num & (((u64)1 << shift) - 1);
    unsigned __int128 sc = (unsigned __int128)fr * p10, half = (unsigned __int128)1 << (shift - 1);
    unsigned __int128 q = sc >> shift, rem = sc & (((unsigned __int128)1 << shift) - 1);
    if (rem > half || (rem == half && (q & 1))) q++;
    if (q == p10) { ip++; q = 0; }
    int n = 0; char t[24]; int k = 0;
    do { t[k++] = (char)('0' + ip % 10); ip /= 10; } while (ip);
    while (k) buf[n++] = t[--k];
    buf[n++] = '.';
    for (int i = decimals - 1; i >= 0; i--) { buf[n + i] = (char)('0' + (u64)(q % 10)); q /= 10; }
    n += decimals; buf[n] = 0;
    return n;
}
static int same(const char *a, const char *b) { while (*a && *a == *b) { a++; b++; } return *a == *b; }

static int ints32(void) {
    int good = 0;
    for (int i = 0; i < 50; i++) { u32 v = t32_u32(); if (v == E32_INT[i]) good++; else { pstr("FAIL tinymt32 int "); pdec(i); pstr(": "); pdec(v); pstr("\n"); } }
    pstr("tinymt32, init(1), integers: "); pdec(good); pstr(" of 50 match\n");
    return good == 50;
}
