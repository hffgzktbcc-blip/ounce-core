#ifndef SIP_C
#define SIP_C 2
#endif
#ifndef SIP_D
#define SIP_D 4
#endif
#define ROTL(x, b) (((x) << (b)) | ((x) >> (64 - (b))))
#define SIPROUND do { \
    v0 += v1; v1 = ROTL(v1, 13); v1 ^= v0; v0 = ROTL(v0, 32); \
    v2 += v3; v3 = ROTL(v3, 16); v3 ^= v2; \
    v0 += v3; v3 = ROTL(v3, 21); v3 ^= v0; \
    v2 += v1; v1 = ROTL(v1, 17); v1 ^= v2; v2 = ROTL(v2, 32); } while (0)

static u64 le64(const u8 *p) { u64 r = 0; for (int i = 7; i >= 0; i--) r = (r << 8) | p[i]; return r; }

static u64 siphash(const u8 key[16], const u8 *m, unsigned long n) {
    u64 k0 = le64(key), k1 = le64(key + 8);
    u64 v0 = k0 ^ 0x736f6d6570736575ULL, v1 = k1 ^ 0x646f72616e646f6dULL;
    u64 v2 = k0 ^ 0x6c7967656e657261ULL, v3 = k1 ^ 0x7465646279746573ULL;
    unsigned long full = n & ~7UL;
    for (unsigned long i = 0; i < full; i += 8) {
        u64 w = le64(m + i); v3 ^= w; for (int r = 0; r < SIP_C; r++) SIPROUND; v0 ^= w;
    }
    u64 last = (u64)n << 56;
    for (unsigned long i = 0; i < (n & 7); i++) last |= (u64)m[full + i] << (8 * i);
    v3 ^= last; for (int r = 0; r < SIP_C; r++) SIPROUND; v0 ^= last;
    v2 ^= 0xff; for (int r = 0; r < SIP_D; r++) SIPROUND;
    return v0 ^ v1 ^ v2 ^ v3;
}

int paper_main(void) {
    u8 key[16], msg[64];
    for (int i = 0; i < 16; i++) key[i] = (u8)i;
    for (int i = 0; i < 64; i++) msg[i] = (u8)i;
    int ok = 1;
    ok &= pcheck_u64("paper example, 15 bytes", siphash(key, msg, 15), 0xa129ca6149be45e5ULL, 16);
    int good = 0;
    for (int n = 0; n < 64; n++) {
        u64 h = siphash(key, msg, (unsigned long)n);
        u8 b[8]; for (int i = 0; i < 8; i++) b[i] = (u8)(h >> (8 * i));
        int m = 1; for (int i = 0; i < 8; i++) if (b[i] != KAT[n][i]) m = 0;
        good += m;
        if (!m) { pstr("FAIL length "); pdec(n); pstr(": "); phex_bytes(b, 8); pstr("\n"); }
    }
    pstr("reference vectors: "); pdec(good); pstr(" of 64 match\n");
    ok &= good == 64;
    pstr(ok ? "PASS\n" : "FAIL\n");
    return ok ? 0 : 1;
}
