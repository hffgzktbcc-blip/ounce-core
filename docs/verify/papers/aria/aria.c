static int hexbytes(const char *s, u8 *out) {
    int n = 0;
    for (; s[0] && s[1]; s += 2) {
        int v = 0;
        for (int i = 0; i < 2; i++) { char c = s[i]; v = v * 16 + (c <= '9' ? c - '0' : c >= 'a' ? c - 'a' + 10 : c - 'A' + 10); }
        out[n++] = (u8)v;
    }
    return n;
}

// ---- ARIA (RFC 5794 section 2) ----
#ifndef ARIA_R19
#define ARIA_R19 19            // rotation amount of the first round-key group
#endif
typedef struct { u8 b[16]; } blk;
static blk xor_blk(blk a, blk b) { for (int i = 0; i < 16; i++) a.b[i] ^= b.b[i]; return a; }
static blk rot128(blk x, int n) {          // rotate the 128-bit big-endian value left by n (0 <= n < 128); right by n is left by 128 - n
    u64 hi = 0, lo = 0;
    for (int i = 0; i < 8; i++) { hi = (hi << 8) | x.b[i]; lo = (lo << 8) | x.b[8 + i]; }
    n &= 127;
    if (n >= 64) { u64 t = hi; hi = lo; lo = t; n -= 64; }
    if (n) { u64 h = (hi << n) | (lo >> (64 - n)); u64 l = (lo << n) | (hi >> (64 - n)); hi = h; lo = l; }
    blk r; for (int i = 7; i >= 0; i--) { r.b[i] = (u8)hi; hi >>= 8; r.b[8 + i] = (u8)lo; lo >>= 8; }
    return r;
}
static blk rotl(blk x, int n) { return rot128(x, n); }
static blk rotr(blk x, int n) { return rot128(x, 128 - n); }
static blk SL(blk x, int type) {           // type 1: SB1 SB2 SB3 SB4 repeated; type 2: SB3 SB4 SB1 SB2 repeated
    blk y; static const u8 ORD1[4] = {0, 1, 2, 3}, ORD2[4] = {2, 3, 0, 1};
    for (int i = 0; i < 16; i++) y.b[i] = SB[(type == 1 ? ORD1 : ORD2)[i & 3]][x.b[i]];
    return y;
}
static blk Adiff(blk x) {
    const u8 *p = x.b; blk y;
    y.b[0]  = p[3] ^ p[4] ^ p[6] ^ p[8]  ^ p[9]  ^ p[13] ^ p[14];
    y.b[1]  = p[2] ^ p[5] ^ p[7] ^ p[8]  ^ p[9]  ^ p[12] ^ p[15];
    y.b[2]  = p[1] ^ p[4] ^ p[6] ^ p[10] ^ p[11] ^ p[12] ^ p[15];
    y.b[3]  = p[0] ^ p[5] ^ p[7] ^ p[10] ^ p[11] ^ p[13] ^ p[14];
    y.b[4]  = p[0] ^ p[2] ^ p[5] ^ p[8]  ^ p[11] ^ p[14] ^ p[15];
    y.b[5]  = p[1] ^ p[3] ^ p[4] ^ p[9]  ^ p[10] ^ p[14] ^ p[15];
    y.b[6]  = p[0] ^ p[2] ^ p[7] ^ p[9]  ^ p[10] ^ p[12] ^ p[13];
    y.b[7]  = p[1] ^ p[3] ^ p[6] ^ p[8]  ^ p[11] ^ p[12] ^ p[13];
    y.b[8]  = p[0] ^ p[1] ^ p[4] ^ p[7]  ^ p[10] ^ p[13] ^ p[15];
    y.b[9]  = p[0] ^ p[1] ^ p[5] ^ p[6]  ^ p[11] ^ p[12] ^ p[14];
    y.b[10] = p[2] ^ p[3] ^ p[5] ^ p[6]  ^ p[8]  ^ p[13] ^ p[15];
    y.b[11] = p[2] ^ p[3] ^ p[4] ^ p[7]  ^ p[9]  ^ p[12] ^ p[14];
    y.b[12] = p[1] ^ p[2] ^ p[6] ^ p[7]  ^ p[9]  ^ p[11] ^ p[12];
    y.b[13] = p[0] ^ p[3] ^ p[6] ^ p[7]  ^ p[8]  ^ p[10] ^ p[13];
    y.b[14] = p[0] ^ p[3] ^ p[4] ^ p[5]  ^ p[9]  ^ p[11] ^ p[14];
    y.b[15] = p[1] ^ p[2] ^ p[4] ^ p[5]  ^ p[8]  ^ p[10] ^ p[15];
    return y;
}
static blk FO(blk d, blk rk) { return Adiff(SL(xor_blk(d, rk), 1)); }
static blk FE(blk d, blk rk) { return Adiff(SL(xor_blk(d, rk), 2)); }
static blk from_hex(const char *s) { blk b; hexbytes(s, b.b); return b; }

static blk W[4], EK[17], DK[17];
static int NR;
static void aria_key(const u8 *key, int klen) {          // klen in bytes: 16, 24, 32
    blk KL, KR; for (int i = 0; i < 16; i++) { KL.b[i] = key[i]; KR.b[i] = (16 + i < klen) ? key[16 + i] : 0; }
    blk C1 = from_hex(CKC[0]), C2 = from_hex(CKC[1]), C3 = from_hex(CKC[2]), ck1, ck2, ck3;
    if (klen == 16) { ck1 = C1; ck2 = C2; ck3 = C3; } else if (klen == 24) { ck1 = C2; ck2 = C3; ck3 = C1; } else { ck1 = C3; ck2 = C1; ck3 = C2; }
    W[0] = KL; W[1] = xor_blk(FO(W[0], ck1), KR); W[2] = xor_blk(FE(W[1], ck2), W[0]); W[3] = xor_blk(FO(W[2], ck3), W[1]);
    static const int RR[4] = {ARIA_R19, 31, 61, 31};
    for (int g = 0; g < 4; g++) {
        int r = RR[g];
        for (int j = 0; j < 4; j++) {
            int idx = 4 * g + j;
            blk a = W[j];
            if (g < 2) EK[idx] = j < 3 ? xor_blk(a, rotr(W[j + 1], r)) : xor_blk(rotr(W[0], r), W[3]);
            else EK[idx] = j < 3 ? xor_blk(a, rotl(W[j + 1], r)) : xor_blk(rotl(W[0], r), W[3]);
        }
    }
    EK[16] = xor_blk(W[0], rotl(W[1], 19));
    NR = klen == 16 ? 12 : klen == 24 ? 14 : 16;
    // decryption keys: dk1 = ek{n+1}, dk_i = A(ek{n+2-i}) for i = 2..n, dk{n+1} = ek1
    DK[0] = EK[NR];
    for (int i = 2; i <= NR; i++) DK[i - 1] = Adiff(EK[NR + 1 - i]);
    DK[NR] = EK[0];
}
static blk aria_crypt(blk p, const blk *rk, blk *mid) {  // mid (optional): P1..P(n-1)
    for (int r = 1; r < NR; r++) { p = (r & 1) ? FO(p, rk[r - 1]) : FE(p, rk[r - 1]); if (mid) mid[r - 1] = p; }
    return xor_blk(SL(xor_blk(p, rk[NR - 1]), 2), rk[NR]);
}

static int total, bad;
static void chk(const char *what, int idx, blk got, const char *wanthex) {
    u8 want[16]; hexbytes(wanthex, want); total++;
    int ok = 1; for (int i = 0; i < 16; i++) if (got.b[i] != want[i]) ok = 0;
    if (!ok) { bad++; pstr("FAIL "); pstr(what); pstr(" "); pdec(idx); pstr(": "); phex_bytes(got.b, 16); pstr(" expected "); pstr(wanthex); pstr("\n"); }
}
int paper_main(void) {
    // S-box relations stated in the RFC: SB3 and SB4 are the inverses of SB1 and SB2
    int inv_bad = 0;
    for (int x = 0; x < 256; x++) { if (SB[2][SB[0][x]] != x) inv_bad++; if (SB[3][SB[1][x]] != x) inv_bad++; }
    pstr("SB3/SB4 are the inverses of SB1/SB2: "); pdec(512 - inv_bad); pstr(" of 512 entries\n");
    pcheck_u64("RFC example SB1(0x23)", SB[0][0x23], 0x26, 2); pcheck_u64("RFC example SB4(0xef)", SB[3][0xef], 0xd3, 2);
    if (SB[0][0x23] != 0x26 || SB[3][0xef] != 0xd3) bad++;
    bad += inv_bad;
    // A is an involution (RFC 2.4.3)
    int inv_a = 0; for (int i = 0; i < 16; i++) { blk x; for (int j = 0; j < 16; j++) x.b[j] = (u8)(i == j ? 0x80 + i : 7 * j + 1); blk y = Adiff(Adiff(x)); for (int j = 0; j < 16; j++) if (y.b[j] != x.b[j]) inv_a++; }
    pstr("A(A(x)) == x on 16 test inputs: "); pstr(inv_a ? "FAIL\n" : "PASS\n"); bad += inv_a;

    for (int s = 0; s < 3; s++) {
        u8 key[32]; int kl = hexbytes(KAT[s][0], key);
        blk pt = from_hex(KAT[s][1]), mid[16], ct, back;
        aria_key(key, kl);
        if (s == 0) {
            for (int i = 0; i < 4; i++) chk("W", i, W[i], W128[i]);
            for (int i = 0; i < 13; i++) chk("ek", i + 1, EK[i], E128[i]);
        }
        ct = aria_crypt(pt, EK, mid);
        if (s == 0) for (int i = 0; i < 11; i++) chk("P", i + 1, mid[i], P128[i]);
        chk(s == 0 ? "ciphertext 128-bit key" : s == 1 ? "ciphertext 192-bit key" : "ciphertext 256-bit key", 0, ct, KAT[s][2]);
        back = aria_crypt(ct, DK, 0);
        chk("decrypt", s, back, KAT[s][1]);
    }
    pstr("RFC 5794 Appendix A values compared (W0-W3, ek1-ek13, P1-P11 for the 128-bit key; 3 ciphertexts; 3 decryptions): "); pdec(total); pstr(", mismatches "); pdec(bad); pstr("\n");
    pstr(bad ? "FAIL\n" : "PASS\n");
    return bad ? 1 : 0;
}
