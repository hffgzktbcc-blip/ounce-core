#ifndef ISAAC_S0
#define ISAAC_S0 13        // the four shifts of the generator step are 13 (left), 6 (right), 2 (left), 16 (right)
#endif
#define SZ 256
static u32 mm[SZ], rsl[SZ], ra, rb, rc;
static int cnt;

static u32 ind(u32 x) { return mm[(x >> 2) & (SZ - 1)]; }
static void isaac(void) {
    u32 a = ra, b = rb + (++rc);
    for (int i = 0; i < SZ; i++) {
        u32 x = mm[i];
        u32 m2 = mm[(i + SZ / 2) % SZ];                 // the word half a table away (first half reads the second, then vice versa)
        switch (i & 3) {
        case 0: a ^= a << ISAAC_S0; break;
        case 1: a ^= a >> 6; break;
        case 2: a ^= a << 2; break;
        default: a ^= a >> 16; break;
        }
        a += m2;
        u32 y = ind(x) + a + b;
        mm[i] = y;
        b = ind(y >> 8) + x;
        rsl[i] = b;
    }
    ra = a; rb = b;
}
static void mix8(u32 *v) {                              // the 8-word mixing step used by the initialisation
    static const signed char sh[8] = {-11, 2, -8, 16, -10, 4, -8, 9};   // negative: shift left, positive: shift right
    for (int k = 0; k < 8; k++) {
        u32 n = v[(k + 1) & 7];
        v[k] ^= sh[k] < 0 ? n << -sh[k] : n >> sh[k];
        v[(k + 3) & 7] += v[k];
        v[(k + 1) & 7] += v[(k + 2) & 7];
    }
}
static void isaac_init_from_rsl(void) {                 // seed words are in rsl[]
    u32 v[8];
    ra = rb = rc = 0;
    for (int i = 0; i < 8; i++) v[i] = 0x9e3779b9U;     // the golden ratio
    for (int i = 0; i < 4; i++) mix8(v);
    for (int pass = 0; pass < 2; pass++) {
        for (int i = 0; i < SZ; i += 8) {
            for (int k = 0; k < 8; k++) v[k] += pass == 0 ? rsl[i + k] : mm[i + k];
            mix8(v);
            for (int k = 0; k < 8; k++) mm[i + k] = v[k];
        }
    }
    isaac();            // first block (discarded by the author's -DNEVER test, used first by randtest)
    cnt = SZ;
}
static u32 isaac_rand(void) {                           // the author's rand() macro consumes each block from its last word to its first
    if (cnt == 0) { isaac(); cnt = SZ; }
    return rsl[--cnt];
}

int paper_main(void) {
    int ok = 1;
    // --- test 1: all-zero seed, two further blocks printed in order ---
    for (int i = 0; i < SZ; i++) rsl[i] = 0;
    isaac_init_from_rsl();
    int good = 0;
    for (int blk = 0; blk < 2; blk++) {
        isaac();
        for (int j = 0; j < SZ; j++) {
            u32 want = EXPECT[blk * SZ + j];
            if (rsl[j] == want) good++;
            else { pstr("FAIL randvect word "); pdec(blk * SZ + j); pstr(": "); phex(rsl[j], 8); pstr(" expected "); phex(want, 8); pstr("\n"); }
        }
    }
    pstr("zero seed (randvect.txt): "); pdec(good); pstr(" of 512 words match\n");
    ok &= good == 512;
    // --- test 2: text seed, 2560 values drawn with the reference rand() ---
    static const char text[] = "This is <i>not</i> the right mytext.";
    for (int i = 0; i < SZ; i++) rsl[i] = 0;
    for (unsigned i = 0; i < sizeof(text); i++) rsl[i / 4] |= (u32)(unsigned char)text[i] << (8 * (i % 4));   // memcpy into a little-endian word array
    isaac_init_from_rsl();
    good = 0;
    for (int j = 0; j < 2560; j++) {
        u32 v = isaac_rand();
        if (v == EXPECT2[j]) good++;
        else if (j < 20) { pstr("FAIL randseed word "); pdec(j); pstr(": "); phex(v, 8); pstr(" expected "); phex(EXPECT2[j], 8); pstr("\n"); }
    }
    pstr("text seed (randseed.txt): "); pdec(good); pstr(" of 2560 words match\n");
    ok &= good == 2560;
    pstr(ok ? "PASS\n" : "FAIL\n");
    return ok ? 0 : 1;
}
