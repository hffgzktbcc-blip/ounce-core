static u32 a[SALE_N + 1];

int paper_main(void) {
    static char out[NDIG + 2];
    for (int i = 2; i <= SALE_N; i++) a[i] = 1;
    out[0] = '2';
    for (int d = 1; d < NDIG; d++) {
        u32 carry = 0;
        for (int i = SALE_N; i >= 2; i--) {
            u32 t = 10 * a[i] + carry;
            a[i] = t % (u32)i;
            carry = t / (u32)i;
        }
        out[d] = (char)('0' + carry);
    }
    int first = -1;
    for (int i = 0; i < NDIG; i++) if (out[i] != E_DIGITS[i]) { first = i; break; }
    pstr("first 50 digits: "); paper_write(out, 50); pstr("\n");
    pstr("last 10 digits (9991-10000): "); paper_write(out + 9990, 10); pstr("\n");
    if (first < 0) pstr("PASS spigot output equals the 10000 digits of e in OEIS A001113\n");
    else { pstr("FAIL first difference at digit "); pdec(first + 1); pstr("\n"); }
    return first < 0 ? 0 : 1;
}
